#!/usr/bin/env bash
# Reachability probe, run INSIDE each sandbox as the agent. Prints what a
# hostile agent could touch. Compare outputs across microVM / Docker / bwrap.
p() { printf '%-28s %s\n' "$1" "$2"; }
p "uid" "$(id -u) ($(id -un))"
p "hostname" "$(hostname)"
p "kernel" "$(uname -r)"
p "host home (/home/*)" "$(ls -d /home/*/ 2>/dev/null | grep -qv "^/home/agent/$" && echo REACHABLE || echo no)"
p "/dev/kvm" "$([ -e /dev/kvm ] && echo present || echo no)"
p "docker.sock" "$([ -e /var/run/docker.sock ] && echo present || echo no)"
p "rootfs device ro" "$(grep -q ' /mnt ext4 ro' /proc/mounts && echo yes || echo NO)"
p "root is overlay" "$(grep -q '^overlay / overlay' /proc/mounts && echo yes || echo NO)"
p "root fs writable" "$(touch /probe.$$ 2>/dev/null && rm /probe.$$ && echo YES || echo no)"
p "/etc/shadow readable" "$(cat /etc/shadow >/dev/null 2>&1 && echo YES || echo no)"
p "procs visible" "$(ls /proc | grep -c '^[0-9]')"
p "api.anthropic.com direct via proxy (should be denied)" "$(curl -s -o /dev/null -m 10 -w '%{http_code}' https://api.anthropic.com/ || echo unreachable)"
p "broker ANTHROPIC_BASE_URL set" "${ANTHROPIC_BASE_URL:-unset}"
p "broker /v1/models (4xx = reached)" "$(curl -s -o /dev/null -m 10 -w '%{http_code}' -H 'x-api-key: x' "${ANTHROPIC_BASE_URL:-http://0.0.0.0:1}/v1/models" || echo unreachable)"
p "example.com (proxy)" "$(curl -s -o /dev/null -m 10 -w '%{http_code}' https://example.com/ || echo unreachable)"
p "example.com direct" "$(env -i PATH="$PATH" curl -s -o /dev/null -m 3 -w '%{http_code}' https://example.com/ || echo unreachable)"
p "dns direct (<2s)" "$(s=$(date +%s%N); getent hosts example.com >/dev/null 2>&1 && echo RESOLVES || echo "fails in $(( ($(date +%s%N)-s)/1000000 )) ms")"
p "proxy -> host port 22" "$(curl -s -o /dev/null -m 3 -w '%{http_code}' http://172.16.0.1:22/ || echo unreachable)"
p "proxy -> LAN" "$(curl -s -o /dev/null -m 3 -w '%{http_code}' http://192.168.100.1/ || echo unreachable)"
p "proxy -> IP literal" "$(curl -s -o /dev/null -m 5 -w '%{http_code}' https://1.1.1.1/ || echo unreachable)"
p "host gateway ssh" "$(timeout 2 bash -c 'cat < /dev/null > /dev/tcp/172.16.0.1/22' 2>/dev/null && echo OPEN || echo closed)"
p "host lan direct" "$(env -i PATH="$PATH" curl -s -o /dev/null -m 3 -w '%{http_code}' http://192.168.100.1/ || echo unreachable)"
p "sudo" "$(command -v sudo >/dev/null && echo present || echo missing)"
p "cap bounding set" "$(grep CapBnd /proc/self/status | cut -f2)"
p "creds file" "$([ -f ~/.claude/.credentials.json ] && echo present || echo absent)"
p "claude" "$(claude --version 2>/dev/null || echo missing)"
